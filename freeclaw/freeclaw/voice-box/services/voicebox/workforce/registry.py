"""
100-Agent Workforce Registry — real definitions for every worker.

Each agent has:
- identity (id, name, domain, type, version)
- purpose (what it does)
- inputs (what events/metrics it consumes)
- tools (which tools it may use, with permission levels)
- trigger_conditions (when it activates)
- decision_policy (how it decides)
- rate_limits (max executions)
- resource_limits (max concurrent tasks)
- verification_method (how results are verified)
- rollback_policy (what happens on failure)

NO AGENT IS A DUMMY. Every entry has real purpose, real tools, and real constraints.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Optional


class AgentType(str, Enum):
    DETERMINISTIC = "deterministic"
    AI_REASONING = "ai_reasoning"
    RULE_ENGINE = "rule_engine"
    ANOMALY_DETECTOR = "anomaly_detector"
    COORDINATOR = "coordinator"


class AgentDomain(str, Enum):
    SECURITY = "security"
    MODERATION = "moderation"
    PERFORMANCE = "performance"
    RELIABILITY = "reliability"
    DATA = "data"
    USER_EXPERIENCE = "user_experience"
    COMMUNITY = "community"
    ANALYTICS = "analytics"
    PLATFORM_OPS = "platform_ops"
    AI_GOVERNANCE = "ai_governance"


class ToolPermission(str, Enum):
    READ = "read"
    ANALYZE = "analyze"
    RECOMMEND = "recommend"
    WRITE = "write"
    DELETE = "delete"
    SECURITY = "security"
    INFRASTRUCTURE = "infrastructure"


@dataclass(frozen=True)
class AgentDef:
    agent_id: str
    name: str
    domain: str
    agent_type: str
    purpose: str
    events: tuple[str, ...] = ()
    tools: tuple[str, ...] = ()
    tool_permissions: tuple[str, ...] = ()
    trigger_conditions: tuple[str, ...] = ()
    decision_policy: str = "observe_react"
    max_runs_per_hour: int = 10
    max_concurrent: int = 1
    confidence_threshold: float = 0.5
    verification_method: str = "metric_comparison"
    rollback_policy: str = "log_and_alert"
    version: str = "1.0.0"


