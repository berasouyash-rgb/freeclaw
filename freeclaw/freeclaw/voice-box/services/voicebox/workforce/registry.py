# ─── Event → Agent routing ───────────────────────────────────────────

def agents_for_event(event_type: str) -> list[AgentDef]:
    """Return all agents that should be notified of a given event type."""
    result = []
    for agent in ALL_AGENTS:
        if event_type in agent.events:
            result.append(agent)
    return result
